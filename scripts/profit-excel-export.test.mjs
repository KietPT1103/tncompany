import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { build } from 'esbuild';
import ExcelJS from 'exceljs';
const compiled=await build({entryPoints:['src/app/(dashboard)/reports/profit/profitExcelExport.ts'],bundle:true,write:false,format:'cjs',platform:'node',packages:'external',logLevel:'silent'});
const mod={exports:{}};new Function('require','module','exports',compiled.outputFiles[0].text)(createRequire(import.meta.url),mod,mod.exports);
const {buildProfitWorkbook}=mod.exports;
const inputs={salary:200000,electricity:10000,water:5000,other:999999,marketing:0,thienExpense:0,ingredientInventory:1000,debt:2000,costOverrides:{},otherExpenses:[{id:'snow',name:'Dung dịch tuyết',amount:50000},{id:'bubbles',name:'Dung dịch bong bóng',amount:75000}]};
const days=[{date:'2026-11-03',source:{revenue:1000000,billCount:198,sales:Array.from({length:26},(_,i)=>({key:'p'+i,code:'P'+i,name:'Món '+i,quantity:2,unitCost:1000})),vouchers:[{id:'v',code:'PC001',category:'Nguyên liệu',note:'Mua nguyên liệu',amount:50000}]}},{date:'2026-11-04',source:{revenue:100000,billCount:2,sales:[],vouchers:[]}}];
const options={storeName:'Mô hình Cafe',startDate:'2026-11-03',endDate:'2026-11-04',days,inputsByDate:{'2026-11-03':inputs,'2026-11-04':{...inputs,salary:0,electricity:0,water:0,otherExpenses:[],ingredientInventory:0,debt:0}},unsaved:true};
const workbook=buildProfitWorkbook(options);
assert.deepEqual(workbook.worksheets.map(s=>s.name),['Tổng hợp','Theo ngày','Giá vốn món','Các khoản chi']);
const daily=workbook.getWorksheet('Theo ngày');
assert.equal(daily.getCell('M6').result,442000);
assert.equal(daily.getCell('N6').result,557000);
assert.equal(daily.getCell('N8').result,657000);
assert.equal(daily.getCell('N6').formula,'B6-M6+K6-L6');
assert.equal(daily.getCell('H6').value,125000);
assert.equal(daily.getCell('A6').numFmt,'dd/mm/yyyy');
assert.equal(daily.views[0].ySplit,5);
assert.equal(daily.views[0].showGridLines,true,'Gray worksheet gridlines are visible');
assert.equal(daily.getCell('B6').border.left.style,'thin','Data cells have visible gray borders');
assert.equal(daily.getCell('A5').fill.fgColor.argb,'FF064E3B');
assert.ok(daily.autoFilter);
assert.equal(workbook.getWorksheet('Giá vốn món').rowCount,32,'Exports all 26 products, independent of on-screen pagination');
const expenses=workbook.getWorksheet('Các khoản chi');
assert.equal(expenses.getCell('D7').value,'Dung dịch tuyết');
assert.equal(expenses.getCell('F11').result,190000);
const summary=workbook.getWorksheet('Tổng hợp');
const rowFor=(ws,label)=>{let found;ws.eachRow(row=>{if(row.getCell(1).value===label)found=row.number});return found;};
const profitRow=rowFor(summary,'LỢI NHUẬN RÒNG');
assert.equal(summary.getCell(profitRow,6).result,657000);
assert.equal(summary.getCell(rowFor(summary,'    03/11/2026 · Dung dịch tuyết'),6).result,50000,'Summary shows named other expenses with dates');
assert.equal(summary.getCell(rowFor(summary,'    03/11/2026 · Dung dịch bong bóng'),6).result,75000);
assert.ok(summary.getCell('A3').value.includes('chưa lưu'));
const bytes=await workbook.xlsx.writeBuffer();
const reopened=new ExcelJS.Workbook();await reopened.xlsx.load(bytes);
assert.equal(reopened.getWorksheet('Tổng hợp').getCell(profitRow,6).result,657000,'Cached formula results survive serialization');
assert.equal(reopened.getWorksheet('Các khoản chi').getCell('F7').value,50000,'Amounts remain numeric');
assert.equal(reopened.getWorksheet('Theo ngày').getCell('B6').border.right.color.argb,'FFD1D5DB','Gray borders persist in the downloaded file');
for(const ws of reopened.worksheets)assert.equal(ws.views[0].showGridLines,true);
const single=buildProfitWorkbook({...options,endDate:options.startDate,days:[days[0]]}).getWorksheet('Tổng hợp');
assert.equal(single.getCell(rowFor(single,'    Dung dịch tuyết'),6).result,50000,'Single-day summary lists expenses directly by name');
assert.throws(()=>buildProfitWorkbook({...options,inputsByDate:{...options.inputsByDate,'2026-11-03':{...inputs,water:null}}}),/nhập đủ/);
const loss=buildProfitWorkbook({...options,days:[{...days[0],source:{...days[0].source,revenue:0}}]});
assert.equal(loss.getWorksheet('Theo ngày').getCell('N6').font.color.argb,'FFB91C1C');
assert.equal(loss.getWorksheet('Theo ngày').getCell('O6').result,0,'Zero revenue does not produce division errors');
console.log('PASS profit Excel: 4 styled sheets, full period and products, itemized costs, formulas and cached values, numeric money, print/freeze/filter, loss/zero, incomplete input guard');
