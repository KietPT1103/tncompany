<?php
declare(strict_types=1);
require_once __DIR__.'/../public/api/_lib/stores.php';
require_once __DIR__.'/../public/api/_lib/takeaway_print_jobs.php';
function check(bool $ok,string $message): void { if(!$ok) throw new RuntimeException($message); }
function rejects(callable $fn): void { try {$fn();} catch(DomainException $e) {return;} throw new RuntimeException('Expected rejection'); }
$pdo=new PDO('sqlite::memory:',null,null,[PDO::ATTR_ERRMODE=>PDO::ERRMODE_EXCEPTION,PDO::ATTR_DEFAULT_FETCH_MODE=>PDO::FETCH_ASSOC]);
$pdo->exec('CREATE TABLE stores(id TEXT PRIMARY KEY,name TEXT,created_at DATETIME DEFAULT CURRENT_TIMESTAMP,updated_at DATETIME DEFAULT CURRENT_TIMESTAMP)');
$pdo->exec("INSERT INTO stores(id,name) VALUES('cart','Xe'),('other','Other')");
stores_ensure_schema($pdo);
$store=stores_save($pdo,['role'=>'admin'],'cart',['isTakeAway'=>true,'takeawayPrintingEnabled'=>true]);
check($store['takeawayPrintingEnabled'],'setting saved');
takeaway_print_ensure_schema($pdo);
$bill=['id'=>'B1','storeId'=>'cart','status'=>'completed','total'=>65000,'items'=>[
 ['name'=>'Trà đào','quantity'=>2,'price'=>25000,'note'=>'Ít đá'],['name'=>'Bánh','quantity'=>1,'price'=>15000]]];
$pdo->beginTransaction(); takeaway_print_enqueue($pdo,$store,$bill); $pdo->commit();
takeaway_print_enqueue($pdo,$store,$bill);
$jobs=takeaway_print_list($pdo,'cart');
check(count($jobs)===4,'one receipt and three labels, no duplicates');
$labels=array_values(array_filter($jobs,fn($j)=>$j['kind']==='label'));
check(count($labels)===3 && count(array_filter($labels,fn($j)=>($j['document']['item']['note']??'')==='Ít đá'))===2,'labels preserve notes');
check(count(takeaway_print_list($pdo,'other'))===0,'store isolation');
$first=takeaway_print_claim($pdo,'cart','PC',['receipt']);
check($first['item']['kind']==='receipt','kind routing');
check(takeaway_print_claim($pdo,'cart','PC2',['receipt'])['item']===null,'exclusive claim');
rejects(fn()=>takeaway_print_finish($pdo,'other',$first['item']['id'],$first['claimToken'],'printed',''));
rejects(fn()=>takeaway_print_finish($pdo,'cart',$first['item']['id'],'wrong','printed',''));
takeaway_print_finish($pdo,'cart',$first['item']['id'],$first['claimToken'],'printed','');
$label=takeaway_print_claim($pdo,'cart','PC',['label']);
check($label['item']['document']['labelNumber']===1,'labels claimed in unit order');
takeaway_print_finish($pdo,'cart',$label['item']['id'],$label['claimToken'],'uncertain','Check paper');
rejects(fn()=>takeaway_print_retry($pdo,'cart',$first['item']['id']));
takeaway_print_retry($pdo,'cart',$label['item']['id']);
check(takeaway_print_claim($pdo,'cart','PC',['receipt'])['item']===null,'label retry never repeats receipt');
$bill['id']='B2'; $bill['items'][0]['quantity']=1.5;
takeaway_print_enqueue($pdo,$store,$bill);
$warnings=array_filter(takeaway_print_list($pdo,'cart'),fn($j)=>$j['billId']==='B2' && $j['status']==='failed');
check(count($warnings)===1,'fractional line flagged, never rounded');
$store['takeawayPrintingEnabled']=false; $bill['id']='B3';
check(takeaway_print_enqueue($pdo,$store,$bill)===false,'opt out');
$store['takeawayPrintingEnabled']=true; $bill['id']='ROLLBACK';
$pdo->beginTransaction();takeaway_print_enqueue($pdo,$store,$bill);$pdo->rollBack();
check(!takeaway_print_has_receipt($pdo,'cart','ROLLBACK'),'queue rolls back with bill transaction');
$bill['id']='STALE'; $bill['items']=[['name'=>'Nước','quantity'=>1]];
takeaway_print_enqueue($pdo,$store,$bill);
$stale=takeaway_print_claim($pdo,'cart','PC',['receipt']);
$pdo->prepare("UPDATE takeaway_print_jobs SET updated_at='2000-01-01 00:00:00' WHERE id=?")->execute([$stale['item']['id']]);
$next=takeaway_print_claim($pdo,'cart','PC2',['receipt']);
check(($next['item']['id']??null)!==$stale['item']['id'],'expired claim never automatically replays');
takeaway_print_finish($pdo,'cart',$stale['item']['id'],$stale['claimToken'],'printed','');
$s=$pdo->prepare('SELECT status FROM takeaway_print_jobs WHERE id=?');$s->execute([$stale['item']['id']]);
check($s->fetchColumn()==='printed','late acknowledgement resolves expired claim');
check(count(takeaway_print_list($pdo,'cart',0,'B1'))===4,'filter by bill');
check(takeaway_print_list($pdo,'cart',200)===[],'pagination offset');
$recover=takeaway_print_claim($pdo,'cart','PC',['label']);
takeaway_print_finish($pdo,'cart',$recover['item']['id'],$recover['claimToken'],'uncertain','crash');
takeaway_print_retry($pdo,'cart',$recover['item']['id']);
check(takeaway_print_finish($pdo,'cart',$recover['item']['id'],$recover['claimToken'],'printed','',true)===false,'retired ack discarded without blocking or changing retried job');
$legacy=new PDO('sqlite::memory:',null,null,[PDO::ATTR_ERRMODE=>PDO::ERRMODE_EXCEPTION,PDO::ATTR_DEFAULT_FETCH_MODE=>PDO::FETCH_ASSOC]);
$legacy->exec('CREATE TABLE takeaway_print_jobs(id TEXT PRIMARY KEY,store_id TEXT,bill_id TEXT,job_key TEXT UNIQUE,kind TEXT,status TEXT,document_json TEXT,claim_token TEXT,terminal_name TEXT,error TEXT,created_at DATETIME,updated_at DATETIME)');
takeaway_print_ensure_schema($legacy);
check(in_array('queue_order',array_column($legacy->query('PRAGMA table_info(takeaway_print_jobs)')->fetchAll(),'name'),true),'legacy queue schema upgrades before indexing');
echo "Takeaway printing tests passed\n";
